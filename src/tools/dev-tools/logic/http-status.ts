/** Numeric query matches code prefixes; text matches name or meaning. */
export function searchStatus(query: string): HttpStatus[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...HTTP_STATUS];
  if (/^\d+$/.test(q)) return HTTP_STATUS.filter((s) => String(s.code).startsWith(q));
  return HTTP_STATUS.filter((s) => s.name.toLowerCase().includes(q) || s.meaning.toLowerCase().includes(q));
}
